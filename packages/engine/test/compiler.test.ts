import { expect, it } from "vitest";
import { SceneSpec, World } from "@moco/spec";
import { compileScene, checkTimelines, sequencesFrom } from "../src/generator/compiler.ts";
import { testWorld, setup, section, advance, approveNext } from "./helpers.ts";

const scene = () => SceneSpec.parse({ shotId: "s01", durationFrames: 61, background: { id: "harbour" }, actors: [], captions: [], stage: { camera: "medium", place: "dock", subject: "hero", players: [{ id: "hero", model: "hero", at: [0,0,0] }] } });
it("expands reusable motion to shot timing without mutating its source", () => {
  const input = scene(); input.stage!.players[0]!.sequence = "wave";
  const vocabulary = { entries: [{ id: "wave", source: "ep-01/s01", durationFrames: 31, poseKeys: [{ atFrame: 0, turn: { head: [0,0,0] as [number,number,number] } }, { atFrame: 30, turn: { head: [0,30,0] as [number,number,number] } }] }] };
  const result = compileScene(input, vocabulary);
  expect(result.issues).toEqual([]);
  expect(result.spec.stage!.players[0]!.poseKeys![1]!.atFrame).toBe(60);
  expect(input.stage!.players[0]!.poseKeys).toBeUndefined();
  expect(sequencesFrom(result.spec, "ep-02")[0]!.source).toBe("ep-02/s01");
});
it("rejects unknown sequences, overlapping controls, invalid joints and unordered keys", () => {
  const input = scene(); input.stage!.sequence = "missing";
  expect(compileScene(input).issues[0]!.path).toBe("stage.sequence");
  const player = input.stage!.players[0]!;
  player.to = [1,0,0];
  player.motionKeys = [{ atFrame: 2, at: [0,0,0], facing: 0 }, { atFrame: 2, at: [1,0,0], facing: 0 }];
  player.poseKeys = [{ atFrame: 0, turn: { missing: [0,0,0] } }, { atFrame: 61, turn: {} }];
  expect(checkTimelines(input, World.parse(testWorld())).map((issue) => issue.problem).join()).toMatch(/joint does not exist/);
  expect(checkTimelines(input).length).toBe(3);
});

it("saves successful scene timelines as a revisioned series vocabulary", async () => {
  const { engine } = await setup({
    bible: () => ({ cast: [], style: { palette: [], captionStyle: "bold", mood: "adventure" } }),
    world: () => testWorld(),
    shots: (request) => ({ shots: Array.from({ length: 14 }, (_, i) => ({ id: `s${String(i + 1).padStart(2,"0")}`, fromWord: i * 8, intent: "A sailor listens", characters: ["hero"], location: "harbour" })) }),
    scene: (request) => {
      const brief = section<{ shotId: string; durationFrames: number; voiceoverWords: {text:string;startFrame:number;endFrame:number}[] }>(request.prompt, "Shot brief");
      const spec = scene(); spec.shotId = brief.shotId; spec.durationFrames = brief.durationFrames;
      spec.stage!.camera = ["wide","medium","close"][Number(brief.shotId.slice(1)) % 3]!;
      spec.stage!.players[0]!.poseKeys = [{ atFrame: 0, turn: { head: [0,0,0] } }, { atFrame: brief.durationFrames - 1, turn: { head: [0,15,0] } }];
      spec.captions = brief.voiceoverWords.map((word) => ({ ...word, emphasis: false }));
      return spec;
    },
  });
  const id = await engine.createSeries({ idea: "A sailor listens", language: "en", episodes: 1 });
  for (let i = 0; i < 4; i++) { await advance(engine, id); await approveNext(engine, id); }
  await advance(engine, id);
  const artifact = await engine.readArtifact({ seriesId: id, file: "artifacts/vocabulary.json" }) as { data: { entries: { source: string }[] } };
  expect(artifact.data.entries).toHaveLength(14);
  expect(artifact.data.entries[0]!.source).toBe("ep-01/s01");
});

it("validates against all parts generated by the character designer, including neck", () => {
  const raw = testWorld();
  const world = World.parse({ ...raw, models: raw.models.map((model, i) => i ? model : { ...model, character: { build: "average", skin: "#c08060", hair: { style: "short", colour: "#222222" }, top: { kind: "shirt", colour: "#336699" }, bottom: { kind: "trousers", colour: "#333333" } } }) });
  const spec = scene();
  spec.stage!.players[0]!.poseKeys = [{ atFrame: 0, turn: { neck: [0,0,0] } }, { atFrame: 60, turn: { neck: [0,10,0] } }];
  expect(checkTimelines(spec, world)).toEqual([]);
});
